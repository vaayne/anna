// toolgen has two declaration sources and one intermediate representation.
//
// The first source is an `x-agent-tool` annotation on an HTTP operation, which
// is where a tool belongs when the capability already has a REST contract:
//
//	x-agent-tool: { tool: "goal", action: "create" }
//
// or a list when one operation backs several tool actions:
//
//	x-agent-tool:
//	  - { tool: "scheduler", resource: "job", action: "update" }
//	  - { tool: "scheduler", resource: "job", action: "pause", fixed: { enabled: false }, body: false }
//	  - { tool: "scheduler", resource: "job", action: "resume", fixed: { enabled: true }, body: false }
//
// The second source is api/spec/agent-tools/*.yaml, for capabilities that have
// no HTTP operation at all (a session send, a skill load). Inventing an
// endpoint just to hang a tool off it would be a lie about the contract; those
// tools declare their schema directly and still go through this generator.
//
// Both sources produce []toolDecl, which is validated as a whole (globally
// unique names, provider-legal names, snake_case properties) and then rendered
// per family.
//
// Annotation modifiers:
//   - fixed: service-owned constants, removed from the model input.
//   - restrict: narrows a property's enum without changing the HTTP API; the
//     first value becomes the default.
//   - require/optional: change requiredness in the tool schema only.
//   - add: tool-only properties. For a batch action they belong to each item.
//   - omit: drops a property from the tool input without touching the HTTP API.
//   - rename: renames a property (and its required entry) in the tool input.
//   - body: false: take path/query parameters only, ignore the request body.
//   - batch: wrap the request body in an array property of that name.
//   - name_override: an explicit tool name, for the rare case the default
//     family_resource_action grammar reads wrong (see rules/agent-tools.md §4).
func main() {
	if err := run(inputPath, standaloneDir, outputRoot); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func run(input, declDir, outRoot string) error {
	data, err := os.ReadFile(input)
	if err != nil {
		return fmt.Errorf("read %s: %w", input, err)
	}
	doc, err := parseDoc(data)
	if err != nil {
		return err
	}
	if err := mergeComponentSchemas(doc, componentsPath); err != nil {
		return err
	}
	decls, err := collectOperationTools(doc)
	if err != nil {
		return err
	}
	standalone, err := collectStandaloneTools(declDir, doc)
	if err != nil {
		return err
	}
	decls = append(decls, standalone...)
	if err := validate(decls); err != nil {
		return err
	}
	outputs := groupByOutput(decls)
	expected := map[string]bool{}
	for _, key := range sortedKeysOf(outputs) {
		group := outputs[key]
		family := group[0].Family
		content, err := renderTool(family, group[0].Package, group)
		if err != nil {
			return err
		}
		root := group[0].Package.Root
		if root == "" {
			root = "internal"
		}
		outDir := filepath.Join(outRoot, root, group[0].Package.Dir)
		if err := os.MkdirAll(outDir, 0o755); err != nil {
			return err
		}
		out := filepath.Join(outDir, generatedFileName(family))
		expected[out] = true
		if err := os.WriteFile(out, content, 0o644); err != nil {
			return fmt.Errorf("write %s: %w", out, err)
		}
	}
	// Keep the supported roots explicit. Deriving them from the current output
	// set leaves stale generated files behind when the last family in a root is
	// removed from the declarations.
	for _, root := range []string{"internal", "plugins"} {
		rootPath := filepath.Join(outRoot, root)
		if _, err := os.Stat(rootPath); os.IsNotExist(err) {
			continue
		} else if err != nil {
			return err
		}
		if err := pruneStaleOutputs(rootPath, expected); err != nil {
			return err
		}
	}
	return nil
}

// generatedFileName gives every family its own output. Families that share a
// package must never overwrite each other or share generated identifiers.
func generatedFileName(family string) string { return "tool_" + family + "_gen.go" }

// generatedMarker is the header every rendered file carries. Pruning keys off
// it rather than off the file name, so a hand-written tool_<family>_gen.go is
// never deleted.
const generatedMarker = "// Code generated by go run ./internal/tools/toolgen; DO NOT EDIT."

// pruneStaleOutputs deletes generated files no declaration produces any more.
// Without it, deleting the last declaration of a family leaves its tool_gen.go
// behind: it keeps compiling, keeps exporting ActionTools(), and keeps the
// removed tool registered. The drift check cannot see it either, because
// nothing changed.
func pruneStaleOutputs(outRoot string, expected map[string]bool) error {
	return filepath.WalkDir(outRoot, func(path string, entry fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if entry.IsDir() || !strings.HasPrefix(entry.Name(), "tool_") || !strings.HasSuffix(entry.Name(), "_gen.go") || expected[path] {
			return nil
		}
		data, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		if !bytes.HasPrefix(data, []byte(generatedMarker)) {
			return nil
		}
		fmt.Fprintf(os.Stderr, "toolgen: removing stale %s (no declaration generates it)\n", path)
		return os.Remove(path)
	})
}

type openAPIDoc struct {
	Paths      map[string]any `yaml:"paths"`
	Components struct {
		Schemas map[string]any `yaml:"schemas"`
	} `yaml:"components"`
}

type actionSpec struct {
	Tool         string `yaml:"tool"`
	Resource     string `yaml:"resource"`
	Action       string `yaml:"action"`
	NameOverride string `yaml:"name_override"`
	Description  string `yaml:"description"`
	// Input replaces the operation request body for this tool only. It lets a
	// model-facing schema be stricter than the corresponding HTTP contract.
	Input         any               `yaml:"input"`
	Fixed         map[string]any    `yaml:"fixed"`
	Restrict      map[string][]any  `yaml:"restrict"`
	Require       []string          `yaml:"require"`
	Optional      []string          `yaml:"optional"`
	PreserveEmpty []string          `yaml:"preserve_empty"`
	Add           map[string]any    `yaml:"add"`
	Omit          []string          `yaml:"omit"`
	Rename        map[string]string `yaml:"rename"`
	Body          *bool             `yaml:"body"`
	Batch         string            `yaml:"batch"`
}

// useBody reports whether the request body contributes to the tool input.
// It is opt-out rather than inferred: a pause action that fixes the one body
// field it needs must say `body: false`, so the reader of the annotation can
// see why the remaining body fields are gone.
func (s actionSpec) useBody() bool { return s.Body == nil || *s.Body }

type domainPackage struct {
	Root    string
	Dir     string
	Package string
	// PluginID and Namespace are authored at this composition root for the
	// generated families that are real Go plugins. Empty values mean the
	// family is a core tool and keeps its existing name.
	PluginID  string
	Namespace string
	// PrefixGeneratedSymbols makes this family safe to generate alongside other
	// families or hand-written action-shaped types in the same package.
	PrefixGeneratedSymbols bool
	// Split emits one tool per action instead of one union tool. Providers
	// reject oneOf/const at the top level of a function schema, so a union tool
	// cannot express per-action parameters: every action's fields are hoisted
	// together and a wrong one is only caught after the call. Splitting is the
	// only way to get the provider to validate arguments before dispatch.
	Split bool
}

